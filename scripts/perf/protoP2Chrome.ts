/**
 * THROWAWAY prototype tool (T3 #5971, Option C step 4, P2): generates
 * src/node/orpc/workspaceFirstViewChrome.ts from the live seeded workspace page at 412 px.
 *
 * It opens `<url>` (a `xum server` with the neutral seed, scripts/perf/neutralSeed.ts) in Chrome,
 * waits for the live transcript, and turns the live DOM into a JSON tree: [tag, attrs, ...children],
 * strings for text, {s: name} for slots the early script fills from workspace data. User data
 * (workspace title, project, branch, model, messages) never lands in the tree: those nodes become
 * slots or empty. Message rows become templates. The early script builds the tree with
 * createElement/createElementNS/setAttribute/text nodes only.
 *
 * Run: node --experimental-strip-types scripts/perf/protoP2Chrome.ts http://127.0.0.1:<port>/workspace/a1b2c3d4e5
 */
import fs from "node:fs";
import path from "node:path";
import { chromium } from "playwright-core";

const url = process.argv[2];
if (!url) throw new Error("usage: protoP2Chrome.ts <seeded workspace url>");

const browser = await chromium.launch({ executablePath: "/usr/bin/google-chrome" });
const page = await browser.newPage({ viewport: { width: 412, height: 823 } });
await page.goto(url);
await page.waitForSelector('[data-testid=message-window][data-loaded="true"] [data-message-id]');
await page.waitForTimeout(500);

const out = await page.evaluate(() => {
  type Node = string | { s: string } | [string, Record<string, string> | 0, ...Node[]];
  const SKIP =
    "[id^=DndDescribedBy],[id^=DndLiveRegion],#review-immersive-root,.mobile-hide-right-sidebar," +
    "input[type=file],.sr-only,[data-model-display-tooltip]";
  // Ids, a11y and test hooks go: the copy is inert and must not duplicate live hooks.
  const DROP =
    /^(id|role|tabindex|title|for|name|aria-(?!hidden).*|data-testid|data-message-id|data-tutorial|data-state|data-autofocus-state|data-loaded|autocomplete|spellcheck)$/;
  const slots = new Map<Element, Node[]>();
  const setSlot = (sel: string, kids: Node[], scope: ParentNode = document) => {
    for (const el of scope.querySelectorAll(sel)) slots.set(el, kids);
  };
  setSlot("[data-testid=workspace-title]", [{ s: "title" }]);
  setSlot("[data-testid=workspace-footer-bar] span.font-mono.truncate", [{ s: "project" }]);
  setSlot("[data-testid=workspace-footer-bar] button span.truncate", []); // branch
  setSlot("[data-component=Model] span.truncate", []); // model
  setSlot("[data-thinking-label]", []);
  setSlot("[data-context-usage-percent]", []);
  setSlot('[aria-label$="skills loaded"] span.absolute', []);
  const log = document.querySelector("[role=log]")!;
  const conv = (el: Element): Node => {
    const tag = el.tagName === "MAIN" ? "div" : el.localName; // one <main>: the boot loader's
    const attrs: Record<string, string> = {};
    for (const a of el.attributes) if (!DROP.test(a.name)) attrs[a.name] = a.value;
    const kids: Node[] = [];
    if (slots.has(el)) kids.push(...slots.get(el)!);
    else
      for (const c of el.childNodes) {
        if (c.nodeType === 3) kids.push(c.textContent!);
        else if (c.nodeType === 1) {
          const e = c as Element;
          if (e.matches(SKIP)) continue;
          if (el === log && e.matches("[data-transcript-message]")) {
            if (!kids.some((k) => typeof k === "object" && !Array.isArray(k) && k.s === "rows"))
              kids.push({ s: "rows" });
            continue;
          }
          kids.push(conv(e));
        }
      }
    return [tag, Object.keys(attrs).length ? attrs : 0, ...kids];
  };
  const row = (sel: string) => {
    const el = [...document.querySelectorAll(sel)].at(-1)!.closest("[data-transcript-message]")!;
    setSlot(".markdown-content > div", [{ s: "md" }], el);
    setSlot("[data-message-timestamp]", [{ s: "ts" }], el);
    return conv(el);
  };
  return {
    chrome: conv(document.querySelector("#root")!.firstElementChild!),
    user: row("[data-message-id^=user]"),
    assistant: row("[data-message-id^=assistant]"),
    copy: conv(document.querySelector(".code-copy-button")!),
  };
});
await browser.close();

const json = JSON.stringify(out).replaceAll("<", "\\u003c");
const file = path.join(import.meta.dirname, "../../src/node/orpc/workspaceFirstViewChrome.ts");
fs.writeFileSync(
  file,
  `// GENERATED by scripts/perf/protoP2Chrome.ts from the live seeded page at 412 px. Do not edit.\n` +
    `// THROWAWAY prototype (T3 #5971 C step 4). Trusted capture: no user data, slots only.\n` +
    `export const WORKSPACE_VIEW_TREE_JSON = ${JSON.stringify(json)};\n`
);
console.log(`wrote ${file}: ${json.length} chars`);
