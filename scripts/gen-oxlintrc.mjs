#!/usr/bin/env node
// Generates .oxlintrc.json from eslint.config.mjs, so `make lint` can run oxlint locally while
// CI keeps running the full type-aware ESLint config (`make lint-full`).
//
// A cold type-aware ESLint run peaks at ~7.6 GiB; several agents running it at once OOM-killed
// shared workspaces. oxlint with the same syntax rules and the custom `local/*` rules lints the
// whole repo in seconds at well under 1 GiB. What oxlint cannot check (type-aware rules,
// `no-restricted-syntax`, LOCAL_SKIPPED_RULES) only fails in CI.
//
// oxlint overrides have no `ignores` and no extglobs, so translating the ESLint blocks one by one
// loses precision. Instead, ESLint resolves the effective config of every lint file, files with
// the same config share one override that lists them, and @oxlint/migrate translates each
// config's rules. Every file therefore gets exactly the rules ESLint applies to it, where oxlint
// supports them. A file that is not listed (ignored by ESLint, or created after the config was
// generated) gets no rules, which is why scripts/lint.sh calls this script with --if-stale before
// every run: the config is regenerated whenever its inputs or the set of lint files change.
//
// Usage: node scripts/gen-oxlintrc.mjs [--if-stale] [output path, default .oxlintrc.json]

import crypto from "node:crypto";
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const { listLintFiles } = require("./lib/lint_targets.js");

const LOCAL_PLUGIN = { name: "local", specifier: "./eslint-local-rules.mjs" };

// Inputs that change the generated config besides the set of lint files.
const CONFIG_INPUTS = [
  "eslint.config.mjs",
  "eslint-local-rules.mjs",
  "scripts/gen-oxlintrc.mjs",
  "node_modules/.installed",
];

// Rules oxlint does not enforce locally. CI still runs them through ESLint.
const LOCAL_SKIPPED_RULES = new Set([
  // Needs the TypeScript checker, which oxlint JS plugins do not get; it would silently pass.
  "local/no-required-member-typeof-guard",
  // oxlint looks through `as` casts and reports ~40 sites that ESLint accepts.
  "no-unsafe-optional-chaining",
  // oxlint also reports defaulted parameters with literal types (`x: "a" = "a"`).
  "@typescript-eslint/no-inferrable-types",
]);

const HEADER_PREFIX =
  "// Generated by scripts/gen-oxlintrc.mjs from eslint.config.mjs. Do not edit. Inputs: ";

function isOff(value) {
  const severity = Array.isArray(value) ? value[0] : value;
  return severity === 0 || severity === "off";
}

const SEVERITY_NAMES = ["off", "warn", "error"];

/** ESLint resolves `"error"` to `[2]`; write it back in the form the configs use. */
function normalizeRuleValue(value) {
  const [severity, ...options] = Array.isArray(value) ? value : [value];
  const name = SEVERITY_NAMES[severity] ?? severity;
  return options.length > 0 ? [name, ...options] : name;
}

/**
 * oxlint matches override `files` as globs. Repo paths have no glob syntax today; if one ever
 * does, each special character becomes `?`, which still matches the path itself.
 */
function pathToGlob(file) {
  return file.replace(/[*?[\]{}()!\\]/g, "?");
}

function mergeSettings(settingsList) {
  const settings = {};
  for (const fileSettings of settingsList) {
    for (const [plugin, value] of Object.entries(fileSettings ?? {})) {
      settings[plugin] = { ...settings[plugin], ...value };
    }
  }
  // oxlint needs an explicit version where eslint-plugin-react can detect it.
  if (settings.react?.version === "detect") {
    const reactPackage = JSON.parse(fs.readFileSync(require.resolve("react/package.json"), "utf8"));
    settings.react = { ...settings.react, version: reactPackage.version };
  }
  return settings;
}

/**
 * @param {{ cwd?: string, files?: string[], eslintOptions?: object }} [options]
 *   `eslintOptions` replaces how ESLint loads its config (tests pass an inline config).
 */
export async function generateOxlintConfig({
  cwd = ROOT,
  files = listLintFiles(cwd),
  eslintOptions = {},
} = {}) {
  const [{ ESLint }, { default: migrate }] = await Promise.all([
    import("eslint"),
    import("@oxlint/migrate"),
  ]);
  const eslint = new ESLint({ cwd, ...eslintOptions });

  const groups = new Map();
  const settingsList = [];
  for (const file of files) {
    const config = await eslint.calculateConfigForFile(file);
    // ESLint ignores this file, so oxlint gives it no rules either.
    if (config === undefined) continue;
    const rules = {};
    const localRules = {};
    for (const [name, value] of Object.entries(config.rules ?? {})) {
      if (isOff(value) || LOCAL_SKIPPED_RULES.has(name)) continue;
      (name.startsWith("local/") ? localRules : rules)[name] = normalizeRuleValue(value);
    }
    const globals = config.languageOptions?.globals ?? {};
    const key = JSON.stringify([rules, localRules, globals]);
    if (!groups.has(key)) {
      const plugins = { ...config.plugins };
      delete plugins.local;
      groups.set(key, { files: [], rules, localRules, plugins, globals });
    }
    groups.get(key).files.push(file);
    settingsList.push(config.settings);
  }

  const overrides = [];
  for (const group of groups.values()) {
    const migrated = await migrate(
      [{ plugins: group.plugins, languageOptions: { globals: group.globals }, rules: group.rules }],
      undefined,
      { jsPlugins: true, typeAware: false }
    );
    const jsPlugins = [...(migrated.jsPlugins ?? [])];
    if (Object.keys(group.localRules).length > 0) jsPlugins.push(LOCAL_PLUGIN);
    overrides.push({
      files: group.files.map(pathToGlob),
      ...(migrated.plugins?.length ? { plugins: migrated.plugins } : {}),
      ...(jsPlugins.length ? { jsPlugins } : {}),
      ...(migrated.env ? { env: migrated.env } : {}),
      ...(migrated.globals ? { globals: migrated.globals } : {}),
      rules: { ...migrated.rules, ...group.localRules },
    });
  }

  return {
    $schema: "./node_modules/oxlint/configuration_schema.json",
    // Only the rules listed per file run: no default plugins or categories.
    plugins: [],
    categories: { correctness: "off" },
    settings: mergeSettings(settingsList),
    overrides,
  };
}

function inputsKey(root, files) {
  const hash = crypto.createHash("sha256");
  for (const input of CONFIG_INPUTS) {
    const file = path.join(root, input);
    hash.update(`${input}\0${fs.existsSync(file) ? fs.statSync(file).mtimeMs : "missing"}\0`);
  }
  hash.update(files.join("\0"));
  return hash.digest("hex");
}

function readKey(output) {
  try {
    const firstLine = fs.readFileSync(output, "utf8").split("\n", 1)[0];
    return firstLine.startsWith(HEADER_PREFIX) ? firstLine.slice(HEADER_PREFIX.length) : null;
  } catch {
    return null;
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const ifStale = args.includes("--if-stale");
  const output = path.resolve(ROOT, args.find((arg) => !arg.startsWith("--")) ?? ".oxlintrc.json");
  const files = listLintFiles(ROOT);
  const key = inputsKey(ROOT, files);
  if (!(ifStale && readKey(output) === key)) {
    console.log(`Generating ${path.relative(ROOT, output)} from eslint.config.mjs...`);
    const config = await generateOxlintConfig({ files });
    // Write then rename, so a concurrent `make lint` never reads a partial file. oxlint accepts
    // comments in its JSON config but rejects unknown keys, so the key lives in a comment.
    const temporary = `${output}.${process.pid}.tmp`;
    fs.writeFileSync(temporary, `${HEADER_PREFIX}${key}\n${JSON.stringify(config, null, 2)}\n`);
    fs.renameSync(temporary, output);
  }
}
