import { expect, test } from "bun:test";
import { readFile } from "fs/promises";
import * as path from "path";

// sources.ts is on every page's first load (the command palette builds its actions
// eagerly), so everything its static imports reach ships in main-*.js. #6133 made it
// reach tool-card code through mcpAppViewsStore -> toolUtils.tsx (+7.4 KB br, #6349).
// Dynamic `import()` edges load later, so the walk follows static imports only.
// Paths are kept with "/" separators so the substring checks below also hold on Windows,
// where path.join and Bun.resolveSync return backslashes (fs and the resolver accept both).
const toPosix = (file: string): string => file.replaceAll("\\", "/");
const ENTRY = toPosix(path.join(import.meta.dir, "sources.ts"));
const FORBIDDEN = [
  "/src/browser/features/Tools/Shared/ToolPrimitives",
  "/src/browser/features/Tools/Shared/toolUtils",
  "/src/browser/features/Messages/useStickyExpand",
];
// Generated by the build (src/version.ts), absent in a fresh checkout.
const MAY_BE_UNRESOLVED = new Set(["@/version"]);

async function staticImportGraph(entry: string): Promise<{
  parents: Map<string, string | null>;
  unresolved: Set<string>;
}> {
  const transpiler = new Bun.Transpiler({ loader: "tsx" });
  const parents = new Map<string, string | null>([[entry, null]]);
  const unresolved = new Set<string>();
  const queue = [entry];
  while (queue.length > 0) {
    const file = queue.shift()!;
    if (!/\.[jt]sx?$/.test(file) || file.includes("/node_modules/")) continue;
    // Type-only imports are erased by the transpiler, so they are not listed here.
    for (const imp of transpiler.scanImports(await readFile(file, "utf-8"))) {
      if (imp.kind !== "import-statement") continue;
      let resolved: string;
      try {
        resolved = toPosix(Bun.resolveSync(imp.path, path.dirname(file)));
      } catch {
        unresolved.add(imp.path);
        continue;
      }
      if (parents.has(resolved)) continue;
      parents.set(resolved, file);
      queue.push(resolved);
    }
  }
  return { parents, unresolved };
}

function chainTo(parents: Map<string, string | null>, file: string): string {
  const chain: string[] = [];
  for (let at: string | null | undefined = file; at != null; at = parents.get(at)) {
    chain.push(path.relative(process.cwd(), at));
  }
  return chain.join(" <- ");
}

test("the command palette's static imports do not reach tool-card code", async () => {
  const { parents, unresolved } = await staticImportGraph(ENTRY);
  // The walk must follow the edge that caused #6349, or a passing result proves nothing.
  expect([...parents.keys()].some((file) => file.endsWith("/mcpAppViewsStore.ts"))).toBe(true);
  expect([...unresolved].filter((spec) => !MAY_BE_UNRESOLVED.has(spec))).toEqual([]);
  const reached = [...parents.keys()].filter((file) => FORBIDDEN.some((f) => file.includes(f)));
  expect(reached.map((file) => chainTo(parents, file))).toEqual([]);
});
