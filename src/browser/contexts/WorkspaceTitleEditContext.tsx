import React, { createContext, useContext, useState, useCallback, useRef } from "react";
import type { Result } from "@/common/types/result";
import { getErrorMessage } from "@/common/utils/errors";
import { getVisibleWorkspaceIds } from "@/browser/utils/ui/workspaceDomNav";

interface TitleEditResult {
  success: boolean;
  error?: string;
}

type RegenerateTitleResult = Result<{ title: string }, string>;

interface TitleEditContextValue {
  editingWorkspaceId: string | null;
  requestEdit: (workspaceId: string, currentTitle: string) => boolean;
  confirmEdit: (workspaceId: string, newTitle: string) => Promise<TitleEditResult>;
  cancelEdit: () => void;
  /** Workspace IDs whose titles are currently being generated by AI. */
  generatingTitleWorkspaceIds: ReadonlySet<string>;
  /** Wraps an async title-generation call with loading state management. */
  wrapGenerateTitle: (workspaceId: string, fn: () => Promise<RegenerateTitleResult>) => void;
}

const TitleEditContext = createContext<TitleEditContextValue | null>(null);

interface TitleEditProviderProps {
  children: React.ReactNode;
  onUpdateTitle: (
    workspaceId: string,
    newTitle: string
  ) => Promise<{ success: boolean; error?: string }>;
}

/**
 * Whether the edit in progress refuses a request for another workspace. An edit whose row the
 * sidebar does not render (an inactive sub-agent, a collapsed project: F2 or the menu bar's Edit
 * title can start one) has no input to finish it, so it must not block the next edit (#6202).
 */
function blocksOtherEdits(editingWorkspaceId: string | null, workspaceId: string): boolean {
  if (editingWorkspaceId === null || editingWorkspaceId === workspaceId) return false;
  return getVisibleWorkspaceIds().includes(editingWorkspaceId);
}

/** The one open title edit. One value, so a save can tell whether it is still the open edit. */
function useOpenEdit() {
  const [edit, setEdit] = useState<{ workspaceId: string; originalTitle: string } | null>(null);
  // A save settles after its await: by then the user can have moved on to another workspace's
  // edit (blocksOtherEdits lets one start while the saving row is hidden). Close only our own.
  const finishEdit = useCallback((workspaceId: string) => {
    setEdit((current) => (current?.workspaceId === workspaceId ? null : current));
  }, []);
  return {
    editingWorkspaceId: edit?.workspaceId ?? null,
    originalTitle: edit?.originalTitle ?? "",
    setEdit,
    finishEdit,
  };
}

export const TitleEditProvider: React.FC<TitleEditProviderProps> = ({
  children,
  onUpdateTitle,
}) => {
  const { editingWorkspaceId, originalTitle, setEdit, finishEdit } = useOpenEdit();

  const requestEdit = useCallback(
    (workspaceId: string, currentTitle: string): boolean => {
      // Only allow one workspace to be edited at a time.
      if (blocksOtherEdits(editingWorkspaceId, workspaceId)) {
        return false;
      }

      setEdit({ workspaceId, originalTitle: currentTitle });
      return true;
    },
    [editingWorkspaceId, setEdit]
  );

  const confirmEdit = useCallback(
    async (workspaceId: string, newTitle: string): Promise<TitleEditResult> => {
      const trimmedTitle = newTitle.trim();

      // Short-circuit if title hasn't changed
      if (trimmedTitle === originalTitle) {
        finishEdit(workspaceId);
        return { success: true };
      }

      if (!trimmedTitle) {
        return { success: false, error: "Title cannot be empty" };
      }

      const result = await onUpdateTitle(workspaceId, trimmedTitle);

      if (result.success) {
        finishEdit(workspaceId);
      }

      return result;
    },
    [originalTitle, onUpdateTitle, finishEdit]
  );

  const cancelEdit = useCallback(() => {
    setEdit(null);
  }, [setEdit]);

  // --- Generate title loading state ---
  const [generatingTitleWorkspaceIds, setGeneratingTitleWorkspaceIds] = useState<Set<string>>(
    () => new Set()
  );
  const regeneratingWorkspaceIdsRef = useRef<Set<string>>(new Set());

  const wrapGenerateTitle = useCallback(
    (workspaceId: string, fn: () => Promise<RegenerateTitleResult>) => {
      // Ignore duplicate triggers while a regeneration is already in flight for this workspace.
      if (regeneratingWorkspaceIdsRef.current.has(workspaceId)) {
        return;
      }

      regeneratingWorkspaceIdsRef.current.add(workspaceId);
      setGeneratingTitleWorkspaceIds((current) => {
        if (current.has(workspaceId)) {
          return current;
        }
        const next = new Set(current);
        next.add(workspaceId);
        return next;
      });

      void Promise.resolve()
        .then(() => fn())
        .then((result) => {
          if (!result.success && typeof window !== "undefined") {
            window.alert(result.error);
          }
        })
        .catch((error: unknown) => {
          if (typeof window !== "undefined") {
            window.alert(getErrorMessage(error));
          }
        })
        .finally(() => {
          regeneratingWorkspaceIdsRef.current.delete(workspaceId);
          setGeneratingTitleWorkspaceIds((current) => {
            if (!current.has(workspaceId)) {
              return current;
            }
            const next = new Set(current);
            next.delete(workspaceId);
            return next;
          });
        });
    },
    []
  );

  const value: TitleEditContextValue = {
    editingWorkspaceId,
    requestEdit,
    confirmEdit,
    cancelEdit,
    generatingTitleWorkspaceIds,
    wrapGenerateTitle,
  };

  return <TitleEditContext.Provider value={value}>{children}</TitleEditContext.Provider>;
};

export const useTitleEdit = (): TitleEditContextValue => {
  const context = useContext(TitleEditContext);
  if (!context) {
    throw new Error("useTitleEdit must be used within a TitleEditProvider");
  }
  return context;
};
